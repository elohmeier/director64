    port = game.data["port"]
    return {
        "slug": game.slug,
        "title": game.data["title"],
        "source": {
            "id": game.source["id"],
            "file": game.source["file"],
            "sha256": game.source["sha256"],
            "bytes": game.source["bytes"],
            "kind": game.source["kind"],
        },
        "port": {
            key: port[key]
            for key in (
                "director_version",
                "media_root",
                "entry_movie",
                "extended_d6",
                "launcher_movie",
                "native_compatibility",
                "asset_postprocessor",
            )
            if key in port
        },
        "policy": json.loads((game.directory / "host/source-policy.json").read_text()),
        "save_files": web["save_files"],
    }


