def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def web_profile(game: GameSpec) -> dict:
    """The game's browser profile, games/<slug>/web.toml. The runtime is
    built for the port's Director family (family_defines)."""
    game.require_port()
    path = game.directory / "web.toml"
    if not path.is_file():
        raise ValueError(f"{game.slug}: no browser profile (games/{game.slug}/web.toml)")
    profile = tomllib.loads(path.read_text())
    names = profile.get("save_files")
    # A game without player saves says so (saves = false) and lists none.
    saves = profile.get("saves", True)
    if (
        profile.get("schema_version") != 1
        or not isinstance(names, list)
        or saves not in (True, False)
        or bool(names) != saves
        or not all(isinstance(n, str) and n and n.isascii() and '"' not in n for n in names)
    ):
        raise ValueError(f"{path}: invalid browser profile")
    return profile


def abi_digest(root: Path) -> bytes:
    """The runtime ABI a package binds to (docs/package-format.md): name ids and
    opcodes are positions in these two files."""
    digest = hashlib.sha256()
    for name in ("runtime/lingo/names.txt", "runtime/lingo/lingo_bytecode.h"):
        digest.update((root / name).read_bytes())
    return digest.digest()[:16]


def profile_header(game: GameSpec, web: dict) -> str:
    port = game.data["port"]
    names = ", ".join(json.dumps(name) for name in web["save_files"])
    abi = ",".join(f"0x{b:02x}" for b in abi_digest(game.root))
    return (
        "// Generated by director64 web; do not edit.\n"
        "#ifndef DIRECTOR64_WEB_PROFILE_H\n#define DIRECTOR64_WEB_PROFILE_H\n"
        f"#define DIRECTOR64_ENTRY_MOVIE {json.dumps(port['entry_movie'])}\n"
        f"#define DIRECTOR64_SAVE_FILES {names}\n"
        f"#define DIRECTOR64_ABI {{{abi}}}\n"
        "#endif\n"
    )


def sources(game: GameSpec, linked: bool = False) -> list[str]:
    work = game.work.relative_to(game.root).as_posix()
    runtime = [
        "platforms/web/web_main.c",
        "platforms/web/web_runtime.c",
        "platforms/web/compositor.c",
        "runtime/lingo/lingo_runtime.c",
        "runtime/director/director.c",
        "runtime/director/shape.c",
        "runtime/interaction/input.c",
        "runtime/interaction/pointer.c",
    ]
    adapter = sorted(
        p.relative_to(game.root).as_posix()
        for p in (game.directory / "runtime").glob("*.c")
        if p.name != "director_replay.c"
    )
    if not linked:
        return [*runtime, "runtime/package/package.c", *adapter]
    generated = sorted(
        p.relative_to(game.root).as_posix()
        for pattern in ("aot/c/*.c", "director/c/*_scene.c")
        for p in game.work.glob(pattern)
    )
    return [*runtime, *adapter, *generated, f"{work}/director/c/registry.c"]


def compile_command(game: GameSpec, output: Path, linked: bool = False) -> list[str]:
    """The profile runtime's emcc command; `output` holds gen/ and receives
    director64.mjs and director64.wasm."""
    work = game.work.relative_to(game.root).as_posix()
    generated = output.relative_to(game.root).as_posix()
    includes = [
        "runtime",
        "runtime/director",
        "runtime/lingo",
        "runtime/interaction",
        "runtime/storage",
        "runtime/package",
        "platforms/web",
        f"games/{game.slug}/runtime",
        f"games/{game.slug}/probe",
        "platforms/native",
        f"{generated}/gen",
    ]
    if linked:
        includes.append(f"{work}/aot/c")
    exports = EXPORTS if linked else EXPORTS + PACKAGE_EXPORTS
    return [
        "emcc",
        "-std=c17",
        "-O2",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-pedantic",
        *(f"-I{p}" for p in includes),
        *family_defines(game),
        *game_defines(game),
        *([] if linked else ["-DDIRECTOR64_PACKAGE"]),
        *sources(game, linked),
        "--js-library",
        "platforms/web/library.js",
        "-sMODULARIZE=1",
        "-sEXPORT_ES6=1",
        "-sEXPORT_NAME=createDirector64",
        "-sENVIRONMENT=web,node",
        "-sALLOW_MEMORY_GROWTH=1",
        "-sINITIAL_MEMORY=64MB",
        "-sSTACK_SIZE=8MB",
        "-sEXPORTED_FUNCTIONS=" + ",".join("_" + name for name in exports),
        "-sEXPORTED_RUNTIME_METHODS=ccall,UTF8ToString,HEAPU8,HEAPU32,HEAP32",
        "-o",
        f"{generated}/director64.mjs",
    ]


def git_revision(root: Path) -> dict:
    def git(*args):
        return subprocess.run(
            ["git", *args], cwd=root, capture_output=True, text=True, check=False
        ).stdout.strip()

    return {"commit": git("rev-parse", "HEAD"), "dirty": bool(git("status", "--porcelain"))}


def emscripten(root: Path, engine: str, command: list[str]) -> None:
    subprocess.run(
        [
            engine,
            "run",
            "--rm",
            "--network=none",
            "--user",
            f"{os.getuid()}:{os.getgid()}",
            "--volume",
            f"{root}:/workdir",
            "--workdir",
            "/workdir",
            EMSDK_IMAGE,
            *command,
        ],
        check=True,
    )


def build_runtime(
    game: GameSpec, web: dict, output: Path, engine: str, linked: bool = False
) -> list[str]:
    (output / "gen").mkdir(parents=True, exist_ok=True)
    (output / "gen/web_profile.h").write_text(profile_header(game, web))
    command = compile_command(game, output, linked)
    emscripten(game.root, engine, command)
    return command


