"""Shared build integrity gates for ports without a game-specific ROM validator."""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess

from .rom import (
    ROM_LIMIT,
    ROM_TARGET_MIB,
    RomError,
    dfs_files,
    overlay_symbol_names,
    packed_dfs_names,
    validate_header,
    validate_image_pack,
    validate_size,
    validate_symbols,
)
from .rom_inputs import verify as verify_rom_inputs
from .toolchain import container_engine, inspect_image

STATIC_BUDGET = 2 * 1024 * 1024


def validate_rom(game, profile: str) -> dict:
    """Validate generated bytes and build provenance, without claiming gameplay."""
    if profile not in {"release", "probe"}:
        raise RomError("expected release or probe profile")
    target = game.slug + ("-probe" if profile == "probe" else "")
    build = game.work / "n64" / profile
    source = game.work / "n64" / f"{target}.z64"
    verify_rom_inputs(game, profile, source)
    port = game.data["port"]
    budget = port.get("rom_budget_mib", ROM_TARGET_MIB)
    validate_size(source.stat().st_size, release_budget_mib=budget)
    rom = source.read_bytes()
    metadata = validate_header(
        rom,
        title=port["rom_title"],
        save_type=port["rom_save_type"],
        controller_count=port.get("controller_count", 1),
        expected_metadata=(build / "metadata.ini").read_bytes(),
        release_budget_mib=budget,
    )
    packed = json.loads((game.work / "director/packed.json").read_text())
    sdk = inspect_image(
        game.root, os.environ.get("DIRECTOR64_TOOLCHAIN_IMAGE", "director64-toolchain:local")
    )
    if (
        sdk["Id"] != packed["toolchain"]["image"]
        or sdk.get("Config", {}).get("Labels", {}).get("org.director64.libdragon-commit")
        != packed["toolchain"]["revision"]
    ):
        raise RomError("ROM and assets must use the pinned SDK")
    container = [
        container_engine(), "run", "--rm", "--network=none", "-v",
        f"{game.root}:/workdir:ro", "-w", "/workdir", sdk["Id"],
    ]
    elf = str((build / f"{target}.elf").relative_to(game.root))
    symbols = subprocess.check_output([*container, "mips64-elf-nm", elf], text=True)
    validate_symbols(symbols, profile)
    sizes = subprocess.check_output([*container, "mips64-elf-size", elf], text=True)
    try:
        columns = sizes.splitlines()[-1].split()
        sections = [int(value) for value in columns[:3]]
        if len(sections) != 3 or min(sections) < 0:
            raise ValueError("missing section sizes")
    except (IndexError, ValueError) as error:
        raise RomError("invalid ELF section-size report") from error
    static = sum(sections)
    if static > STATIC_BUDGET:
        raise RomError(f"permanent engine exceeds {STATIC_BUDGET}-byte static memory budget")
    memory = {}
    for name in ("runtime_bytes", "fixed_reserve"):
        match = re.search(rf"^([0-9a-fA-F]+) A director64_{name}$", symbols, re.MULTILINE)
        if not match or int(match[1], 16) <= 0:
            raise RomError(f"ELF lacks N64 memory reservation: {name}")
        memory[name] = int(match[1], 16)
    memory["static_bytes"] = static
    memory["reserved_bytes"] = static + memory["runtime_bytes"] + memory["fixed_reserve"]
    memory["rdram_bytes"] = 8 * 1024 * 1024
    memory["unreserved_bytes"] = memory["rdram_bytes"] - memory["reserved_bytes"]
    if memory["unreserved_bytes"] < 0:
        raise RomError("N64 runtime and minimum display/audio/media reservations exceed RDRAM")
    dfs = (build / f"{target}.dfs").read_bytes()
    if not dfs or rom.count(dfs) != 1:
        raise RomError("DFS must be embedded exactly once")
    files = dfs_files(dfs)
    aot = json.loads((game.work / "aot/c/manifest.json").read_text())
    model = json.loads((game.work / "director/model.json").read_text())
    names = [movie["movie"] for movie in aot["movies"]]
    code = {"code/" + name.replace(".", "_").lower() + ".dso" for name in names}
    if not names or len(code) != len(names):
        raise RomError("overlay manifest has empty or colliding movie identities")
    if set(names) != {movie["name"] for movie in model["movies"]}:
        raise RomError("overlay manifest does not cover the converted movies")
    expected = packed_dfs_names(packed) | code | overlay_symbol_names(aot)
    if set(files) != expected:
        missing, extra = sorted(expected - set(files)), sorted(set(files) - expected)
        raise RomError(f"ROM filesystem differs from manifests: missing={missing}, extra={extra}")
    validate_image_pack(files, packed)
    for name, payload in files.items():
        if payload != (game.work / "filesystem" / name).read_bytes():
            raise RomError(f"embedded resource differs from build input: {name}")
        if (
            name in packed["files"]
            and hashlib.sha256(payload).hexdigest() != packed["files"][name]["sha256"]
        ):
            raise RomError(f"packed asset hash mismatch: {name}")
    return {
        "status": "passing",
        "validation_scope": "ROM build integrity; gameplay and performance are not qualified",
        "profile": profile,
        "source_sha256": game.source["sha256"],
        "director_version": port["director_version"],
        "metadata": metadata,
        "rom_sha256": hashlib.sha256(rom).hexdigest(),
        "rom_bytes": len(rom),
        "rom_budget_bytes": budget * 1024 * 1024,
        "rom_capacity_bytes": ROM_LIMIT,
        "dfs_sha256": hashlib.sha256(dfs).hexdigest(),
        "static_bytes": static,
        "static_budget_bytes": STATIC_BUDGET,
        "memory_reservation": memory,
        "overlays": len(code),
        "compiled_handlers": sum(movie["handlers"] for movie in aot["movies"]),
        "native_functions": sum(movie["native_functions"] for movie in aot["movies"]),
        "bytecode_functions": sum(movie.get("bytecode_functions", 0) for movie in aot["movies"]),
        "largest_overlay_bytes": max(len(files[name]) for name in code),
        "assets": len(packed["files"]),
        "toolchain": packed["toolchain"],
        "approximations": model.get("approximations", []),
        "hardware_qualified": False,
        "original_projector_compared": False,
    }
