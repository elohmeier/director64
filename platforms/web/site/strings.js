export function chooseLanguage(search = globalThis.location?.search ?? "",
  languages = globalThis.navigator?.languages ?? []) {
  const asked = new URLSearchParams(search).get("lang");
  if (asked in STRINGS) return asked;
  for (const tag of languages) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (base in STRINGS) return base;
  }
  return "en";
}

export const language = chooseLanguage();

// The text for `key` with its {placeholders} filled in.
export function t(key, values = {}, lang = language) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key];
  if (text === undefined) throw new Error(`no text for ${key}`);
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

// The page's static texts: data-text sets an element's text, data-label its
// aria-label.
export function translatePage(root = document) {
  root.documentElement.lang = language;
  for (const element of root.querySelectorAll("[data-text]")) {
    // A label wrapping a file input keeps the input.
    const node = [...element.childNodes].find((n) => n.nodeType === 3 && n.textContent.trim());
    if (node) node.textContent = t(element.dataset.text);
    else element.prepend(t(element.dataset.text));
  }
  for (const element of root.querySelectorAll("[data-label]"))
    element.setAttribute("aria-label", t(element.dataset.label));
}

export const keys = (lang) => Object.keys(STRINGS[lang]);
