#!/usr/bin/env python3
"""Build the Flash-era Unicode case table from pinned Unicode 3.2 data.

Inputs: https://www.unicode.org/Public/3.2-Update/UnicodeData-3.2.0.txt
Data license: licenses/unicode.txt. Original Flash Player 32 SWF6/7 probes
confirm simple one-to-one mappings without SpecialCasing expansions or context.
This script never reads game media.
"""
import argparse
import hashlib
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    lower, upper = {}, {}
    for row in args.unicode_data.read_text().splitlines():
        fields = row.split(";")
        cp = int(fields[0], 16)
        if fields[13]:
            lower[cp] = [int(fields[13], 16)]
        if fields[12]:
            upper[cp] = [int(fields[12], 16)]
    lines = ["// Generated by tools/generate_avm1_case.py; Unicode 3.2 data.",
             "// Copyright Unicode, Inc. See licenses/unicode.txt."]
    for path in (args.unicode_data,):
        lines.append(f"// {path.name}: SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}")
    lines += ["#ifndef DIRECTOR64_AVM1_CASE_H", "#define DIRECTOR64_AVM1_CASE_H",
              "typedef struct { uint32_t first, last; int32_t delta; "
              "uint8_t step; } an_case_range_t;"]
    for name, table in (("lower", lower), ("upper", upper)):
        singles = sorted((cp, vals[0] - cp) for cp, vals in table.items() if len(vals) == 1)
        ranges = []
        at = 0
        while at < len(singles):
            start, delta = singles[at]
            end, step = start, 1
            if at + 1 < len(singles) and singles[at + 1][1] == delta:
                step = singles[at + 1][0] - start
            if step > 2:
                step = 1
            at += 1
            while at < len(singles) and singles[at] == (end + step, delta):
                end += step
                at += 1
            ranges.append((start, end, delta, step))
        lines.append(f"static const an_case_range_t an_case_{name}[] = {{")
        lines.extend(f"  {{0x{a:x}, 0x{b:x}, {delta}, {step}}}," for a, b, delta, step in ranges)
        lines.append("};")
    lines += ["#endif", ""]
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
