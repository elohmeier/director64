#!/usr/bin/env python3
"""Encode a synthetic original-player RGB5 quantizer census, never textures.

The census replaces all eight DLL brush resources with generated RGB grid
samples and reads their rendered colors. Inputs and raw receipts stay under
ignored build/. Output contains only indices of the system Windows palette.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import zlib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("observations", type=Path)
    parser.add_argument("windows_palette", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    census = json.loads(args.observations.read_text())
    palette = [tuple(map(int, match)) for match in re.findall(
        r"rgb\(\s*(\d+),\s*(\d+),\s*(\d+)\s*\)", args.windows_palette.read_text())]
    if len(palette) != 256 or len(set(palette)) != 256 or census["count"] != 32768:
        raise SystemExit("expected 256 unique palette entries and 32768 RGB5 observations")
    indices = {color: index for index, color in enumerate(palette)}
    data = bytes(indices[tuple(color)] for color in census["output_rgb"])
    if len(data) != 32768:
        raise SystemExit("incomplete RGB5 census")
    packed = zlib.compress(data, 9)
    lines = ["// Generated by tools/reference/generate_texture_quantizer.py.",
             "// Synthetic Director 8.5.1r104 behavior: RGB5 -> Windows palette index.",
             "// No game texture, DLL bytes or captured image pixels are included.",
             f"// Uncompressed lookup SHA-256: {hashlib.sha256(data).hexdigest()}",
             f"const RGB5_INDICES: &[u8; {len(packed)}] = &["]
    lines += ["    " + ", ".join(f"0x{b:02x}" for b in packed[at:at + 16]) + ","
              for at in range(0, len(packed), 16)]
    lines += ["];", ""]
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
